-- Pass 2: switch rows still unmatched (e.g. switch did not log UPI_TXN_ID) <-> NPCI rows still unmatched,
-- exact on RRN + amount, |time diff| <= matching.pass2_window_s (RECON.SETTINGS). Best (closest) pair wins.
CREATE OR REPLACE TABLE RECON.M2 AS
WITH w AS (SELECT CAST("PARAM_VALUE" AS DECIMAL(18,0)) AS "WIN" FROM "RECON"."SETTINGS" WHERE "PARAM_NAME" = 'pass2_window_s'),
s AS (SELECT * FROM "RAW"."SWITCH_LOG" x
      WHERE NOT EXISTS (SELECT 1 FROM "RECON"."M1" m WHERE m."RRN" = x."RRN" AND m."SW_TS" = x."TXN_TS")),
n AS (SELECT * FROM "RAW"."NPCI_SETTLEMENT" y
      WHERE NOT EXISTS (SELECT 1 FROM "RECON"."M1" m WHERE m."UPI_TXN_ID" = y."UPI_TXN_ID")),
c AS (
  SELECT n."UPI_TXN_ID", s."RRN", s."TXN_TS" AS "SW_TS", s."AMOUNT_PAISE", s."STATUS" AS "SW_STATUS",
         s."RESP_CODE" AS "SW_RESP", n."STATUS" AS "NPCI_STATUS", n."RESP_CODE" AS "NPCI_RESP",
         n."TXN_TYPE", n."PAYEE_BANK", n."SETTLEMENT_DT", n."CYCLE_NO",
         ROW_NUMBER() OVER (PARTITION BY s."RRN", s."TXN_TS" ORDER BY ABS(SECONDS_BETWEEN(n."TXN_TS", s."TXN_TS")), n."UPI_TXN_ID") AS "RN_S",
         ROW_NUMBER() OVER (PARTITION BY n."UPI_TXN_ID" ORDER BY ABS(SECONDS_BETWEEN(n."TXN_TS", s."TXN_TS")), s."TXN_TS") AS "RN_N"
  FROM s JOIN n ON n."RRN" = s."RRN" AND n."AMOUNT_PAISE" = s."AMOUNT_PAISE"
  CROSS JOIN w
  WHERE ABS(SECONDS_BETWEEN(n."TXN_TS", s."TXN_TS")) <= w."WIN"
)
SELECT "UPI_TXN_ID", "RRN", "SW_TS", "AMOUNT_PAISE", "SW_STATUS", "SW_RESP", "NPCI_STATUS", "NPCI_RESP",
       "TXN_TYPE", "PAYEE_BANK", "SETTLEMENT_DT", "CYCLE_NO", 2 AS "MATCH_PASS"
FROM c WHERE "RN_S" = 1 AND "RN_N" = 1;

-- Unified transaction set: matched (pass 1/2) + switch rows with no NPCI record + NPCI rows with no switch row
CREATE OR REPLACE TABLE RECON.TXN AS
SELECT * FROM "RECON"."M1"
UNION ALL SELECT * FROM "RECON"."M2"
UNION ALL
SELECT x."UPI_TXN_ID", x."RRN", x."TXN_TS", x."AMOUNT_PAISE", x."STATUS", x."RESP_CODE",
       CAST(NULL AS VARCHAR(10)), CAST(NULL AS VARCHAR(10)), CAST(NULL AS VARCHAR(10)), CAST(NULL AS VARCHAR(20)),
       CAST(NULL AS DATE), CAST(NULL AS DECIMAL(3,0)), CAST(NULL AS DECIMAL(1,0))
FROM "RAW"."SWITCH_LOG" x
WHERE NOT EXISTS (SELECT 1 FROM "RECON"."M1" m WHERE m."RRN" = x."RRN" AND m."SW_TS" = x."TXN_TS")
  AND NOT EXISTS (SELECT 1 FROM "RECON"."M2" m WHERE m."RRN" = x."RRN" AND m."SW_TS" = x."TXN_TS")
UNION ALL
SELECT y."UPI_TXN_ID", y."RRN", y."TXN_TS", y."AMOUNT_PAISE", CAST(NULL AS VARCHAR(10)), CAST(NULL AS VARCHAR(10)),
       y."STATUS", y."RESP_CODE", y."TXN_TYPE", y."PAYEE_BANK", y."SETTLEMENT_DT", y."CYCLE_NO", CAST(NULL AS DECIMAL(1,0))
FROM "RAW"."NPCI_SETTLEMENT" y
WHERE NOT EXISTS (SELECT 1 FROM "RECON"."M1" m WHERE m."UPI_TXN_ID" = y."UPI_TXN_ID")
  AND NOT EXISTS (SELECT 1 FROM "RECON"."M2" m WHERE m."UPI_TXN_ID" = y."UPI_TXN_ID");
